"""Writes core/mime/bidi-class.js: the bidi direction class of every code point, as the composer's shape check counts
them (app/renderer/src/compose-shape.js), from the Unicode Character Database that this Python carries (unicodedata).

  python3 -I scripts/gen-bidi-class.py core/mime/bidi-class.js

The mapping: L -> L; R, AL -> R; EN -> EN; AN -> AN; LRI, RLI, FSI, PDI -> I; LRE, RLE, LRO, RLO, PDF -> E; every other
class (NSM, BN, WS, ON, ES, ET, CS, B, S) -> neutral. An unassigned code point (no class in this database) is U: the
Electron of the app knows a newer Unicode, whatever the character's real class is there, it counts on its own.
The output is the same file byte for byte for the same Unicode version (test/compose-shape.test.js runs it again).
"""
import sys
import unicodedata

NEUTRAL, L, R, EN, AN, I, U, E = 0, 1, 2, 3, 4, 5, 6, 7
CLASS = {'L': L, 'R': R, 'AL': R, 'EN': EN, 'AN': AN, 'LRI': I, 'RLI': I, 'FSI': I, 'PDI': I, 'LRE': E, 'RLE': E, 'LRO': E, 'RLO': E, 'PDF': E}


def class_of(cp):
    bidi = unicodedata.bidirectional(chr(cp))
    if bidi == '':
        return U
    return CLASS.get(bidi, NEUTRAL)


def main(out):
    starts, classes = [], []
    last = None
    for cp in range(0x110000):
        c = class_of(cp)
        if c != last:
            starts.append(cp)
            classes.append(c)
            last = c
    rows = []
    for i in range(0, len(starts), 16):
        rows.append('  ' + ', '.join(f'{s}, {c}' for s, c in zip(starts[i:i + 16], classes[i:i + 16])) + ',')
    text = '\n'.join([
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// GENERATED by scripts/gen-bidi-class.py, do not edit: python3 -I scripts/gen-bidi-class.py core/mime/bidi-class.js',
        f'// The bidi direction class of every code point, from the Unicode Character Database {unicodedata.unidata_version}',
        '// (through the Python unicodedata module), Unicode License v3. Classes: 0 neutral, 1 L, 2 R (R, AL), 3 EN, 4 AN,',
        '// 5 I (LRI, RLI, FSI, PDI), 6 U (unassigned in this Unicode: the browser may know it), 7 E (LRE, RLE, LRO, RLO, PDF).',
        '// RUNS: pairs of (the first code point of a run, its class), in order; a run lasts until the next one starts.',
        f"export const UNICODE_VERSION = '{unicodedata.unidata_version}'",
        f'export const RUN_COUNT = {len(starts)}',
        'export const RUNS = Object.freeze([',
        *rows,
        '])',
        '',
    ])
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('usage: python3 -I scripts/gen-bidi-class.py <output file>')
    main(sys.argv[1])
